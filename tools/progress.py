#!/usr/bin/env python3
"""Byte-match progress over Miyoo's own code (the embedded SQLite and cJSON are excluded).
Usage: progress.py [--md docs/progress.md] [--matches-md src/MATCHES.md]

Function boundaries come from ghidra/names.tsv: a function's size is the distance to the next
function start (so literal pools count toward it), capped at the end of its code range.
Matched bytes come from src/matches.tsv. If docs/tu-map.tsv exists (lo, hi, name, confidence,
evidence; hex addresses, hi exclusive), progress is also reported per translation unit, and a unit
whose range is "proven" (tools/tusplit.py UNIT_FIXED, set after tools/unitcheck.py printed RESULT
MATCH) and whose src/<name>.cpp (or .c) exists counts whole: every function in it, template tail included.
CI keeps that claim honest by running scripts/run_units.sh on every src/tu_*.cpp and src/tu_*.c.
"""
import argparse
import bisect
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RANGES = [(0x15b20, 0x51b60), (0x11cdc8, 0x150ad8)]   # After PLT/crt, minus libraries, up to libgcc __udivsi3

ap = argparse.ArgumentParser()
ap.add_argument("--md", help="also write a Markdown report here")
ap.add_argument("--matches-md", help="regenerate the src/MATCHES.md table from src/matches.tsv")
a = ap.parse_args()


def tsv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE))


starts = []
with open(os.path.join(ROOT, "ghidra/names.tsv")) as f:
    for line in f:
        addr = line.split("\t", 1)[0]
        try:
            v = int(addr, 16)
        except ValueError:
            continue
        if any(lo <= v < hi for lo, hi in RANGES):
            starts.append(v)
starts.sort()
size = {}
for i, s in enumerate(starts):
    end = next(hi for lo, hi in RANGES if lo <= s < hi)
    if i + 1 < len(starts) and starts[i + 1] < end:
        end = starts[i + 1]
    size[s] = end - s

matches = tsv(os.path.join(ROOT, "src/matches.tsv"))
done = {int(m["addr"], 16) for m in matches}
unknown = sorted(d for d in done if d not in size)

tus, proven = [], []
tu_path = os.path.join(ROOT, "docs/tu-map.tsv")
if os.path.exists(tu_path):
    for t in tsv(tu_path):
        lo, hi = int(t["lo"], 16), int(t["hi"], 16)
        tus.append((lo, hi, t["name"]))
        if t["confidence"] == "proven" and any(os.path.exists(os.path.join(ROOT, "src", t["name"] + x))
                                               for x in (".cpp", ".c")):
            proven.append((lo, hi))
            done |= {s for s in starts if lo <= s < hi}


def stats(lo, hi):
    i, j = bisect.bisect_left(starts, lo), bisect.bisect_left(starts, hi)
    fs = starts[i:j]
    m = [s for s in fs if s in done]
    return len(m), len(fs), sum(size[s] for s in m), sum(size[s] for s in fs)


def pct(x, y):
    return f"{100 * x / y:.2f}%" if y else "-"


rows = []
if tus:
    rows.append("| Translation unit | Range | Functions | Bytes | Done |")
    rows.append("| --- | --- | --- | --- | --- |")
    for lo, hi, name in tus:
        mf, nf, mb, nb = stats(lo, hi)
        mark = " (unit proven)" if (lo, hi) in proven else ""
        rows.append(f"| {name} | {lo:#x}–{hi:#x} | {mf}/{nf} | {mb:,}/{nb:,} | {pct(mb, nb)}{mark} |")
    rows.append("")
mf = sum(stats(lo, hi)[0] for lo, hi in RANGES)
nf = sum(stats(lo, hi)[1] for lo, hi in RANGES)
mb = sum(stats(lo, hi)[2] for lo, hi in RANGES)
nb = sum(stats(lo, hi)[3] for lo, hi in RANGES)
rows.append(f"**Miyoo code:** {mf:,} of {nf:,} functions, {mb:,} of {nb:,} bytes matched ({pct(mb, nb)}): "
            f"{len(proven)} whole units proven by unitcheck, plus single functions from src/matches.tsv elsewhere.")
if not tus:
    rows.append("No docs/tu-map.tsv yet, so there is no per-unit breakdown.")
if unknown:
    rows.append("Not a function start in ghidra/names.tsv: " + ", ".join(f"{u:#x}" for u in unknown))
report = "\n".join(rows)
print(report)

if a.md:
    with open(a.md, "w") as f:
        f.write("# Byte-match progress\n\nGenerated by `tools/progress.py`; do not edit by hand.\n\n" + report + "\n")

if a.matches_md:
    with open(a.matches_md) as f:
        text = f.read()
    head, sep, rest = text.partition("| Function | Address | Size | File |")
    if not sep:
        raise SystemExit(f"{a.matches_md}: function table header not found")
    tail = rest[rest.index("\n\n"):] if "\n\n" in rest else "\n"
    table = ["| Function | Address | Size | File |", "| --- | --- | --- | --- |"]
    for m in sorted(matches, key=lambda m: int(m["addr"], 16)):
        table.append(f"| `{m['signature']}` | {int(m['addr'], 16):#x} | {m['size']} | {m['file']} |")
    with open(a.matches_md, "w") as f:
        f.write(head + "\n".join(table) + tail)
